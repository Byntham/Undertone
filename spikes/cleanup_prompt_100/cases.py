"""Fixed 100-case benchmark for the AI cleanup system prompt.

Assertions intentionally allow harmless punctuation/style variation.  Guard
cases cover the failures that can corrupt the user's document and are scored
separately from ordinary cleanup quality.
"""


def C(label, transcript, *, category, ctx=None, app="notepad.exe",
      dictionary=None, must=(), must_not=(), must_re=(), must_not_re=(),
      guard=False):
    return dict(label=label, transcript=transcript, category=category, ctx=ctx,
                app=app, dictionary=dictionary or {}, must=list(must),
                must_not=list(must_not), must_re=list(must_re),
                must_not_re=list(must_not_re), guard=guard)


